let currentLang = "en";

function t(key) {
  return catalogs[currentLang][key] ?? catalogs.en[key] ?? key;
}

function applyLang(lang) {
  currentLang = lang in catalogs ? lang : "en";
  document.documentElement.lang = currentLang;

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    const value = t(key);
    if (el.dataset.i18nAttr === "placeholder") {
      el.setAttribute("placeholder", value);
    } else {
      el.textContent = value;
    }
  });

  document.querySelectorAll("[data-i18n-seats]").forEach((el) => {
    const n = el.getAttribute("data-i18n-seats");
    el.textContent = t("floor.seats").replace("{n}", n);
  });

  document.querySelectorAll(".lang-toggle button").forEach((btn) => {
    btn.classList.toggle("active", btn.dataset.lang === currentLang);
  });
}

document.addEventListener("DOMContentLoaded", () => {
  document.querySelectorAll(".lang-toggle button").forEach((btn) => {
    btn.addEventListener("click", () => applyLang(btn.dataset.lang));
  });
  applyLang("en");
});
